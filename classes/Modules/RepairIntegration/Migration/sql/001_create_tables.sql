CREATE TABLE IF NOT EXISTS `repair_sync_queue` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `ticket_id` int(11) NOT NULL,
  `ticket_schluessel` varchar(255) NOT NULL,
  `action` enum('status_change','detail_update','email_sent') NOT NULL,
  `payload` text NOT NULL,
  `target_url` varchar(255) NOT NULL,
  `status` enum('pending','processing','completed','failed','permanently_failed') NOT NULL DEFAULT 'pending',
  `retry_count` int(11) NOT NULL DEFAULT 0,
  `max_retries` int(11) NOT NULL DEFAULT 5,
  `next_retry_at` datetime DEFAULT NULL,
  `last_error` text DEFAULT NULL,
  `last_http_code` int(11) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `processed_at` datetime DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `status_next_retry` (`status`, `next_retry_at`),
  KEY `ticket_schluessel` (`ticket_schluessel`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

